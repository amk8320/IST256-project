const mongoose = require('mongoose');

// Create shipping information structure
const shippingSchema = new mongoose.Schema({
    fullName: {
        type: String,
        required: true
    },
    address: {
        type: String,
        required: true
    },
    city: {
        type: String,
        required: true
    },
    state: {
        type: String,
        required: true
    },
    zipCode: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true
    }
});

// Export the Shipping model
module.exports = mongoose.model('Shipping', shippingSchema);